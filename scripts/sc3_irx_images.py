"""SC3's compiled IOP modules as BozoEngine image records: their relocated bytes and their import and export tables.

    python scripts/sc3_irx_images.py <BozoEngine/tools/native_irx> <out.cpp> <stem.json>[:libsd] ...

Each stem is relocate.py's output (stem.json, stem.bin); ":libsd" marks an image whose sound exports native libsd answers
(SC3 has none: LIBSD.IRX is not translated). The output is generated from the player's disc and stays in the build tree.
"""
import sys
from pathlib import Path


def main():
    sys.path.append(sys.argv[1])
    from recompile import Module

    out = Path(sys.argv[2])
    lines = ['// Generated by scripts/sc3_irx_images.py from the disc\'s modules. Do not edit.',
             '#include "sc3_audio.h"', '', 'namespace sc3::audio', '{',
             '    std::vector<bozo::native::irx::Image> images()', '    {',
             '        std::vector<bozo::native::irx::Image> out;']
    for arg in sys.argv[3:]:
        path, _, flag = arg.partition(':')
        m = Module(path)
        exports, imports = m.tables()
        data = ','.join(str(b) for b in m.image)
        lines.append('        {')
        lines.append(f'            static const uint8_t bytes[] = {{{data}}};')
        lines.append(f'            out.push_back({{"{m.name}", 0x{int(m.hash, 16):x}ull, 0x{m.base:x}u, 0x{m.entry:x}u, '
                     f'0x{m.gp:x}u, std::vector<uint8_t>(bytes, bytes + sizeof(bytes)),')
        lines.append('                           {' + ', '.join(f'{{0x{a:x}u, "{lib}", {n}}}'
                                                          for a, (lib, n) in sorted(imports.items())) + '},')
        lines.append('                           {' + ', '.join(f'{{0x{a:x}u, "{lib}", {n}}}'
                                                          for a, (lib, n) in sorted(exports.items())) + '},')
        lines.append(f'                           {"true" if flag == "libsd" else "false"}}});')
        lines.append('        }')
    lines += ['        return out;', '    }', '}', '']
    text = '\n'.join(lines)
    if not out.exists() or out.read_text(encoding='utf-8') != text:
        out.write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
